def teste_z(n, alfa, tipo):
    amostra = np.random.choice(feridos.values, size=n, replace=False)
    media_amostra = amostra.mean()
    z = (media_amostra - media) / (desvio / np.sqrt(n))
    if tipo == "menor":
        z_critico = norm.ppf(alfa)
        p_valor = norm.cdf(z)
        rejeita = z < z_critico
    else:
        z_critico = norm.ppf(1 - alfa)
        p_valor = 1 - norm.cdf(z)
        rejeita = z > z_critico
    return media_amostra, z, z_critico, p_valor, rejeita

